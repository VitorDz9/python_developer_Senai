#A letra e (ou E) significa "vezes 10 elevado a".
#• 💻 Código: print(2e10)
#• 🧠 Significado: \(2 \times 10^{10}\) (o número 2 seguido de 10 zeros)
#• 🖥️ Saída: 20000000000.0

#💡 Regra rápida:
#• e positivo (2e3): Anda com a vírgula para a direita \(\rightarrow \) 3000.0
#• e negativo (2e-3): Anda com a vírgula para a esquerda \(\leftarrow \) 0.002


print(2e10) 

