# RESUMO: ARQUITETURA DE COMPUTADORES E O PROCESSADOR (CPU)
# ==========================================================
# 1. PROCESSADOR (CPU):
#    - É considerado o "cérebro" do computador.
#    - Responsável por executar as instruções dos programas e controlar os dados.
#
# 2. ULA (Unidade Lógica e Aritmética):
#    - É o subcomponente do processador que faz o trabalho "pesado":
#      * Aritmética: Realiza cálculos matemáticos (soma, subtração, multiplicação, divisão, resto %).
#      * Lógica: Faz comparações entre valores (maior, menor, igual) e decisões condicionais.
#
# 3. MEMÓRIA PRINCIPAL (RAM):
#    - Guarda temporariamente os dados e os programas enquanto estão em execução.
#
# 4. DISPOSITIVOS DE ENTRADA E SAÍDA (E/S):
#    - Entrada: Dados que entram no computador (ex: Teclado, Mouse).
#    - Saída: Dados que o computador mostra para o utilizador (ex: Monitor, Impressora).