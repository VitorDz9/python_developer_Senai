# 2. Potenciação (Duas formas diferentes):
#    - Operador nativo (Linha 8): '2**3' calcula 2 elevado a 3 e retorna um número inteiro (8).
#    - Função do módulo (Linha 10): 'math.pow(2, 3)' faz o mesmo cálculo, mas sempre retorna um número float (8.0).
# 
# 3. Raiz Quadrada (Linha 15):
#    - A função 'math.sqrt(25)' calcula a raiz quadrada de 25.
