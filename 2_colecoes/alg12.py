numero = [10,5,1,4,1,6,5,1,3,4,5,1,3]
#toda lista em python começa com 0

print(numero[7])

# OBSERVAÇÕES IMPORTANTES SOBRE O CÓDIGO (Listas e Índices):
# 
# 1. Estrutura de Lista (Linha 1):
#    - A variável 'numero' armazena uma sequência de elementos separados por vírgula dentro de colchetes.
# 
# 2. Índice Base Zero (Linha 2):
#    - Como o seu próprio comentário diz, a contagem de posições (índices) começa em 0.
#    - O primeiro elemento (10) está no índice 0, o segundo (5) no índice 1, e assim por diante.
# 
# 3. Acesso a Elementos por Índice (Linha 4):
#    - 'numero[7]' busca o elemento que ocupa a oitava posição da lista.
#    - Fazendo a contagem a partir do zero ([0]=10, [1]=5, [2]=1, [3]=4, [4]=1, [5]=6, [6]=5, [7]=1), o resultado impresso na tela será o número 1.
